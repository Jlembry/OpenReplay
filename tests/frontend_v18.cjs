const fs=require('fs'), vm=require('vm'), assert=require('assert'), path=require('path');
const src=fs.readFileSync(path.join(__dirname,'../static/app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../static/index.html'),'utf8');
assert(!html.includes('toggleLOS') && !html.includes('losStatus'));
assert(!src.includes('paintSightCones') && !src.includes('meshLOS'));
const begin=src.indexOf('const PRIMARY_WEAPONS='),end=src.indexOf('function renderEquipment(holder,gear)');
assert(begin>=0 && end>begin);
let currentInventory={tick:50,weapons:[],active:'weapon_ak47',armor:0,helmet:false,defuser:false};
let carrier=7;
const context=vm.createContext({state:{tick:50}, loadoutAt:()=>currentInventory,bombCarrierAt:()=>carrier,Math});
vm.runInContext(src.slice(begin,end),context);
function classify(value){return vm.runInContext('inventoryClass('+JSON.stringify(value)+')',context)}
for(const input of ['weapon_hegrenade','weapon_high_explosive_grenade','High Explosive Grenade','HE Grenade'])assert.equal(classify(input),'utility',input);
for(const input of ['weapon_incgrenade','weapon_incendiary_grenade','Incendiary Grenade','Incendiary'])assert.equal(classify(input),'utility',input);
for(const input of ['weapon_c4','C4','C4 Explosive','weapon_bomb'])assert.equal(classify(input),'bomb',input);
currentInventory={tick:50,active:'weapon_c4',weapons:['weapon_ak47','weapon_glock','weapon_knife','weapon_hegrenade','High Explosive Grenade','weapon_incendiary_grenade','weapon_c4','C4 Explosive'],armor:100,helmet:true,defuser:false};
let gear=vm.runInContext('normalizedLoadout(7)',context);
const groups=gear.groups;
assert.equal(groups.filter(x=>x.kind==='bomb').length,1,'C4 must appear exactly once');
assert.equal(groups.filter(x=>x.name==='C4').length,1,'no duplicate C4 labels');
assert(!groups.some(x=>x.kind==='other' && /c4|explosive|incendiary/i.test(x.name)),'no miscategorized explosive items');
assert(groups.filter(x=>x.kind==='utility').length>=3,'HE and incendiary belong in utility');
const order=['primary','pistol','knife','utility','equipment','bomb','other'];
assert(groups.every((x,i)=>!i||order.indexOf(groups[i-1].kind)<=order.indexOf(x.kind)),'display order preserved');
carrier=8;
gear=vm.runInContext('normalizedLoadout(7)',context);
assert(!gear.groups.some(x=>x.kind==='bomb'),'C4 hidden from non-carrier');
carrier=7;
currentInventory.weapons=['weapon_glock'];
gear=vm.runInContext('normalizedLoadout(7)',context);
assert.equal(gear.groups.filter(x=>x.kind==='bomb').length,1,'event-detected carrier gets exactly one C4');
console.log('PASS no LOS, HE/incendiary categorized Utility, C4 once in Bomb, loadout ordering');
