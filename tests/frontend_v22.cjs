const fs=require('fs'), path=require('path'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(path.join(__dirname,'../static/app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../static/index.html'),'utf8');
const styles=fs.readFileSync(path.join(__dirname,'../static/styles.css'),'utf8');
const speedBlock=html.match(/<div id="speedButtons"[^>]*>(.*?)<\/div>/)?.[1];
assert(speedBlock,'speed control exists');
for(const speed of ['0.25','0.5','1','2','4']) assert(speedBlock.includes(`data-speed="${speed}"`));
assert(!src.includes('HE · ≈350u'),'radius label must be removed');
assert(src.includes("circleArea(u.pos,350,'#ffa96b'"),'radius shape remains');
assert(html.includes('id="ctTeamName"')&&html.includes('id="tTeamName"'));
assert(styles.includes('.scoreboard-team-name{flex:1;min-width:0;overflow:hidden'));
const b=src.indexOf('function updateScoreboardTeamNames('),e=src.indexOf('function currentRoundAt(',b);
assert(b>=0&&e>b);
const el={ctTeamName:{textContent:'',title:''},tTeamName:{textContent:'',title:''}};
const state={tick:150, demo:{rounds:[{team_names:{'3':'Vitality','2':'FaZe'}},{team_names:{'3':'FaZe','2':'Vitality'}},{team_names:{}}]}};
const ctx=vm.createContext({state,$:name=>el[name],currentRoundAt:tick=>tick<500?0:tick<900?1:2});
vm.runInContext(src.slice(b,e),ctx);
vm.runInContext('updateScoreboardTeamNames(150)',ctx);
assert.deepEqual([el.ctTeamName.textContent,el.tTeamName.textContent],['Vitality','FaZe']);
vm.runInContext('updateScoreboardTeamNames(700)',ctx);
assert.deepEqual([el.ctTeamName.textContent,el.tTeamName.textContent],['FaZe','Vitality']);
vm.runInContext('updateScoreboardTeamNames(1000)',ctx);
assert.deepEqual([el.ctTeamName.textContent,el.tTeamName.textContent],['COUNTER-TERRORISTS','TERRORISTS']);
assert(src.includes('state.tick+=step*state.demo.tick_rate*state.speed'));
console.log('PASS v22: team names, halftime switching, speed and HE radius');
